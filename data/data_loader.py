"""
OptiHedge-RF: Data Ingestion & Validation Layer (Layer 1)
File: data/data_loader.py

Description:
    Loads offline Parquet files generated by scripts/download_bloomberg_data.py,
    validates schema integrity, calculates mid-prices, and computes annualized
    time-to-maturity (T). Outputs clean DataFrames ready for Layer 2 Valuation.
"""

from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Union
import logging
import numpy as np
import pandas as pd

# Configure Module Logger
logger = logging.getLogger(__name__)
logging.basicConfig(level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s")


@dataclass
class MarketDataRow:
    """Dataclass representing a single tick/bar of clean market data."""
    timestamp: pd.Timestamp
    underlying_symbol: str
    spot_price: float
    spot_bid: float
    spot_ask: float
    dw_symbol: str
    dw_price: float
    dw_bid: float
    dw_ask: float
    time_to_maturity: float  # Annualized (T in years)
    risk_free_rate: float    # Annualized rate (e.g., 0.025 for 2.5%)
    implied_volatility: float # Annualized IV (e.g., 0.30 for 30%)
    volume: int


class DataLoader:
    """
    Data Ingestion Engine for loading, validating, and preprocessing
    historical SET/TFEX market data for Derivative Warrants (DWs).
    """

    REQUIRED_COLUMNS = [
        "timestamp",
        "underlying_symbol",
        "spot_bid",
        "spot_ask",
        "dw_symbol",
        "dw_bid",
        "dw_ask",
        "expiry_date",
        "volume"
    ]

    DEFAULT_FALLBACK_COLUMNS = {
        "risk_free_rate": 0.025,       # Default 2.5% risk-free rate
        "implied_volatility": 0.30     # Default 30% implied volatility
    }

    def __init__(self, data_dir: Union[str, Path] = "data/raw"):
        """
        Initialize DataLoader with raw data directory path.

        Args:
            data_dir (str or Path): Path to raw Parquet storage folder.
        """
        self.data_dir = Path(data_dir)
        if not self.data_dir.exists():
            logger.warning(f"Data directory '{self.data_dir}' does not exist. Creating directory.")
            self.data_dir.mkdir(parents=True, exist_ok=True)

    def load_parquet(self, file_name: str) -> pd.DataFrame:
        """
        Load raw Parquet file from data/raw/ and execute cleaning and calculations.

        Args:
            file_name (str): Name of the parquet file (e.g., 'market_data_ADVANC.parquet')

        Returns:
            pd.DataFrame: Processed market dataframe ready for Layer 2.
        """
        file_path = self.data_dir / file_name
        if not file_path.exists():
            raise FileNotFoundError(f"Market data file not found at: {file_path}")

        logger.info(f"Loading raw market data from {file_path}")
        df = pd.read_parquet(file_path)

        # 1. Validate Schema
        self._validate_schema(df)

        # 2. Ensure Correct Data Types
        df["timestamp"] = pd.to_datetime(df["timestamp"])
        df["expiry_date"] = pd.to_datetime(df["expiry_date"])
        df = df.sort_values("timestamp").reset_index(drop=True)

        # 3. Calculate Mid-Prices
        df["spot_price"] = (df["spot_bid"] + df["spot_ask"]) / 2.0
        df["dw_price"] = (df["dw_bid"] + df["dw_ask"]) / 2.0

        # Fallback for last traded price if bid/ask is zero or NaN
        if "spot_last" in df.columns:
            df["spot_price"] = df["spot_price"].fillna(df["spot_last"])
        if "dw_last" in df.columns:
            df["dw_price"] = df["dw_price"].fillna(df["dw_last"])

        # 4. Calculate Annualized Time to Maturity (T in Years)
        # Using 365.0 days convention for standard DW pricing
        time_diff = (df["expiry_date"] - df["timestamp"]).dt.total_seconds()
        df["time_to_maturity"] = np.maximum(time_diff / (365.0 * 86400.0), 0.0)

        # 5. Populate Default / Fallback Columns if Missing
        for col, default_val in self.DEFAULT_FALLBACK_COLUMNS.items():
            if col not in df.columns or df[col].isnull().all():
                df[col] = default_val
            else:
                df[col] = df[col].fillna(default_val)

        logger.info(f"Successfully processed {len(df)} market records for {df['dw_symbol'].iloc[0] if not df.empty else 'Unknown'}")
        return df

    def _validate_schema(self, df: pd.DataFrame) -> None:
        """Internal helper to validate required columns in loaded Parquet data."""
        missing_cols = [col for col in self.REQUIRED_COLUMNS if col not in df.columns]
        if missing_cols:
            raise KeyError(f"Raw parquet file is missing required columns: {missing_cols}")

    @staticmethod
    def to_row_dataclass(df_row: pd.Series) -> MarketDataRow:
        """
        Helper method to convert a single DataFrame row into a MarketDataRow dataclass instance.

        Args:
            df_row (pd.Series): Single row from the loaded DataFrame.

        Returns:
            MarketDataRow: Structured data object for Layer 2/3 iteration.
        """
        return MarketDataRow(
            timestamp=df_row["timestamp"],
            underlying_symbol=str(df_row["underlying_symbol"]),
            spot_price=float(df_row["spot_price"]),
            spot_bid=float(df_row["spot_bid"]),
            spot_ask=float(df_row["spot_ask"]),
            dw_symbol=str(df_row["dw_symbol"]),
            dw_price=float(df_row["dw_price"]),
            dw_bid=float(df_row["dw_bid"]),
            dw_ask=float(df_row["dw_ask"]),
            time_to_maturity=float(df_row["time_to_maturity"]),
            risk_free_rate=float(df_row["risk_free_rate"]),
            implied_volatility=float(df_row["implied_volatility"]),
            volume=int(df_row["volume"])
        )


